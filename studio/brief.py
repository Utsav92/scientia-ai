"""Grounded briefing built only from a paper's own text: extraction items (with verbatim quotes) + its leading sentences.
Nothing here is generated by a model, so everything shown or spoken downstream can be traced to the source."""
from __future__ import annotations
import re
from common import connect
from extraction.findings import extract_paper, sentences, _QUANT
from .structure import sections as doc_sections
from extraction.compare import entity_overlap


def load_sources(ids: list[str], owners: dict[str, str]) -> list[dict]:
    con, out = connect(), []
    for i in ids:
        d = con.execute("SELECT title,text,year,domain FROM documents WHERE id=? AND owner=?", (i, owners[i])).fetchone()
        out.append({"id": i, "owner": owners[i], "title": d["title"] or "Untitled", "year": d["year"], "domain": d["domain"], "text": d["text"],
                    "extraction": extract_paper(i, owners[i])["extraction"]})
    return out


def _wc(s: str, n: int) -> str: return s if len(s) <= n else s[:n].rsplit(" ", 1)[0] + "…"


def _items(ex: dict, key: str) -> list[dict]:
    v = ex.get(key)
    return [v] if isinstance(v, dict) else list(v or [])


def _pick(ex, key, n): return [{"text": e["text"], "quote": e["quote"]} for e in _items(ex, key)[:n]]


_CONC = re.compile(r"\b(?:in conclusion|we conclude|to conclude|conclusions?|in summary|to summari[sz]e|overall,|thus,|therefore,)\b", re.I)
CAPS = {"research_question": 2, "methodology": 4, "findings": 6, "quantitative_results": 5, "conclusions": 3, "limitations": 3, "future_work": 3}


def paper_brief(src: dict) -> dict:
    """Whole sentences only (never truncated). Sections de-duplicate against each other so a point is not listed under several headings."""
    ex = src["extraction"]; title = src["title"].strip().lower().rstrip(".")
    seen, ents = set(), []
    for e in ex.get("entities", []):
        if e.get("type") == "PHYSICAL_QUANTITY" or re.match(r"^[\d.,\s]+\S{0,5}$", e["text"]): continue   # quantities are shown as stats, not concepts
        if e["canonical"] not in seen: seen.add(e["canonical"]); ents.append(e["text"])
    sents = [x for x in sentences(src["text"]) if x.strip().lower().rstrip(".") != title and not x.lower().startswith(title[:40])]
    abstract = [{"text": x, "quote": x} for x in sents[:6]]
    used: set[str] = set()                                        # sections de-duplicate against each other (the abstract is separate)
    numeric_all = [{"text": e["text"], "quote": e["quote"]} for k in ("quantitative_results", "findings") for e in _items(ex, k) if _QUANT.search(e["text"])]
    numeric_all += [{"text": x, "quote": x} for x in sents if _QUANT.search(x) and not any(x == n["text"] for n in numeric_all)]
    out = {"id": src["id"], "title": src["title"], "year": src["year"], "domain": src["domain"], "abstract": abstract, "numeric": numeric_all[:6], "entities": ents[:12], "sections": doc_sections(src["text"], src["title"])}
    pools = {"research_question": _items(ex, "research_question"), "methodology": _items(ex, "methodology"), "findings": _items(ex, "findings"),
             "quantitative_results": _items(ex, "quantitative_results") + [{"text": x, "quote": x} for x in sents if _QUANT.search(x)],
             "conclusions": [{"text": x, "quote": x} for x in sents if _CONC.search(x)], "limitations": _items(ex, "limitations"), "future_work": _items(ex, "future_work")}
    for k in ("research_question", "methodology", "findings", "quantitative_results", "conclusions", "limitations", "future_work"):
        keep = []
        for it in pools[k]:
            if it["text"] in used: continue
            used.add(it["text"]); keep.append({"text": it["text"], "quote": it["quote"]})
            if len(keep) == CAPS[k]: break
        out[k] = keep
    return out


def build_brief(sources: list[dict]) -> dict:
    papers = [paper_brief(s) for s in sources]
    shared = entity_overlap({s["id"]: s["extraction"] for s in sources})["shared_by_all"] if len(sources) > 1 else []
    title = papers[0]["title"] if len(papers) == 1 else f"{len(papers)} papers compared"
    return {"title": title, "papers": papers, "shared_concepts": shared,
            "note": "Every statement is a verbatim sentence from the source paper (rule-based extraction). Missing sections mean the source did not state them or the rules did not detect them."}
